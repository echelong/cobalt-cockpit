// Diff coverage, Phase 1: every changed line gets exactly one category, a missing line entry is never read as "not
// executable", and the rendered report holds to its wording rules in every state.

const encode = (text: string) => new TextEncoder().encode(text)
const facts = (text: string) => {
  const f = sourceFactsOf(encode(text))
  if ('refuse' in f) throw new Error(f.refuse)
  return f
}
const file = (path: string, text: string, over: Partial<ChangedFile> = {}): ChangedFile => ({
  path, status: 'untracked', kind: 'file', modeOnly: false, binaryPatch: false, added: [], modified: [], deletedLines: 0, generatedByAttribute: false, source: facts(text), ...over,
})
const changedLines = (f: ChangedFile): number[] => f.source === null || 'refuse' in f.source ? [] : f.status === 'untracked' ? Array.from({ length: f.source.lineCount }, (_, k) => k + 1) : [...f.added, ...f.modified]
const clock = { now: () => 0, pause: async () => {} }
const parsed = async (report: string, files: readonly ChangedFile[]): Promise<ParsedLcov> => {
  const r = await parseLcov(encode(report), sfMatcher(new Map(files.map(f => [f.path, new Set(changedLines(f))])), { root: '/work/repo' }), clock)
  if (!r.ok) throw new Error(`refused: ${r.code}`)
  return r
}
const bound = async (report: string, files: readonly ChangedFile[]): Promise<Evidence> => ({ state: 'BOUND', report: await parsed(report, files), notes: [] })
const at = (c: Classification, path: string, line: number): LineVerdict | undefined => c.lines.find(v => v.path === path && v.line === line)
const pick = (c: Classification, path: string, category: string): number[] => c.lines.filter(v => v.path === path && v.category === category).map(v => v.line)

describe('source facts are read from the bytes, with bounded text checks', () => {
  test('blank lines, CRLF ends, ignore comments, the generated marker in the first five lines', () => {
    const f = facts('a\r\n  \t\r\n\u00a0\ncode // c8 ignore next\n\n// @generated\n')
    expect(f.lineCount).toBe(6)
    expect([...f.blank]).toEqual([2, 3, 5])
    expect([...f.pragma]).toEqual([4])
    // a marker on line 6 is past the first five lines
    expect(f.generatedLine).toBeNull()
    expect(facts('// Code generated by x. DO NOT EDIT.\nx\n').generatedLine).toBe(1)
    expect(facts('x\n// Code generated by x\n').generatedLine).toBeNull()
    expect(facts(`${' '.repeat(300)}@generated\n`).generatedLine).toBeNull()
    expect(facts('').lineCount).toBe(0)
    expect(facts('a').lineCount).toBe(1)
    expect(facts('a\n').lineCount).toBe(1)
  })
  test('a lone carriage return, U+2028 or U+2029 makes the line table ambiguous; CRLF does not', () => {
    expect(facts('a\rb\n').lineTableAmbiguous).toBe(true)
    expect(facts('a\u2028b\n').lineTableAmbiguous).toBe(true)
    expect(facts('a\u2029b\n').lineTableAmbiguous).toBe(true)
    expect(facts('a\r\nb\r\n').lineTableAmbiguous).toBe(false)
    expect(facts(SOURCES['src/cr.ts']!).lineTableAmbiguous).toBe(true)
  })
  test('NUL in the first 8,000 bytes or invalid UTF-8 is binary; over 4 MiB is not read', () => {
    expect(sourceFactsOf(new Uint8Array([0x61, 0x00, 0x62]))).toEqual({ refuse: 'BINARY' })
    expect(sourceFactsOf(new Uint8Array([0x61, 0xff]))).toEqual({ refuse: 'BINARY' })
    expect(sourceFactsOf(new Uint8Array(4 * 1024 * 1024 + 1))).toEqual({ refuse: 'SOURCE_TOO_LARGE' })
  })
  test('a 4 MiB first line costs milliseconds, not seconds (N16)', () => {
    const long = encode(`${'Code generated '.repeat(270_000)}\n`)
    const start = Date.now()
    expect('refuse' in sourceFactsOf(long)).toBe(false)
    expect(Date.now() - start).toBeLessThan(500)
  })
})

