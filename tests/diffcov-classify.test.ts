describe('the work a change asks of classification is bounded, and refused whole past a limit', () => {
  const unbound: Evidence = { state: 'UNBOUND', why: 'RUN_NOT_OBSERVED' }
  const lines = (n: number, line = 'x = 1') => `${line}\n`.repeat(n)
  const timed = <T>(work: () => T): { value: T; ms: number } => { const start = Date.now(); const value = work(); return { value, ms: Date.now() - start } }
  test('lines are counted by Git\'s numbering from the bytes, and the count stops past its limit', () => {
    for (const [text, want] of [['', 0], ['a', 1], ['a\n', 1], ['\n\n', 2], ['a\nb', 2], [`a${CR}\nb${CR}\n`, 2]] as const) expect([text, lineCountOf(encode(text))]).toEqual([text, want])
    expect(lineCountOf(encode('\n'.repeat(1000)), 10)).toBe(11)
  })
  test('a newline-dense 4 MiB file is refused by its line count before any line is allocated, in milliseconds', () => {
    expect(sourceFactsOf(encode(lines(11)), { ...CLASSIFY_LIMITS, maxSourceLines: 10 })).toEqual({ refuse: 'SOURCE_TOO_MANY_LINES' })
    const dense = new Uint8Array(4 * 1024 * 1024).fill(0x0a)
    const { value, ms } = timed(() => sourceFactsOf(dense))
    expect('refuse' in value ? value.refuse : `facts for ${value.lineCount} lines`).toBe('SOURCE_TOO_MANY_LINES')
    expect(ms).toBeLessThan(1000)
    // as many lines as the limit is a file like any other; one more is refused
    expect('refuse' in sourceFactsOf(encode(lines(CLASSIFY_LIMITS.maxSourceLines, 'x')))).toBe(false)
    const over = sourceFactsOf(encode(lines(CLASSIFY_LIMITS.maxSourceLines + 1, 'x')))
    expect('refuse' in over ? over.refuse : `facts for ${over.lineCount} lines`).toBe('SOURCE_TOO_MANY_LINES')
  })
  test('facts about lines are bit sets: their size follows the line count, never an entry per line', () => {
    const f = facts(lines(CLASSIFY_LIMITS.maxSourceLines, ''))
    expect(f.lineCount).toBe(CLASSIFY_LIMITS.maxSourceLines)
    expect(f.blank.length).toBe(Math.ceil(CLASSIFY_LIMITS.maxSourceLines / 8))
    expect(f.pragma.length).toBe(Math.ceil(CLASSIFY_LIMITS.maxSourceLines / 8))
    expect(linesIn(f.blank).length).toBe(CLASSIFY_LIMITS.maxSourceLines)
  })
  test('many newline-dense files are each refused, and the change is classified without a line from them', () => {
    const dense = new Uint8Array(4 * 1024 * 1024).fill(0x0a)
    const { value, ms } = timed(() => Array.from({ length: 16 }, (_, k) => ({ ...file(`src/d${k}.ts`, ''), source: sourceFactsOf(dense) })))
    expect(ms).toBeLessThan(5000)
    const c = classify(value, unbound, [])
    expect(c.files.every(r => r.reason === 'SOURCE_TOO_MANY_LINES')).toBe(true)
    expect(c.lines).toEqual([])
  })
  test('every path with line evidence counts: excluded and generated files too, tracked changes by their lengths', () => {
    const tight = { ...CLASSIFY_LIMITS, maxChangedLines: 5 }
    expect(classifyChange([file('README.md', lines(6))], unbound, [], tight)).toEqual({ refuse: 'TOO_MANY_LINES' })
    expect(classifyChange([file('src/g.ts', lines(6), { generatedByAttribute: true })], unbound, [], tight)).toEqual({ refuse: 'TOO_MANY_LINES' })
    expect(classifyChange([file('src/t.ts', lines(10), { status: 'modified', added: [1, 2, 3], modified: [4, 5, 6] })], unbound, [], tight)).toEqual({ refuse: 'TOO_MANY_LINES' })
    // files with no line evidence cost nothing
    expect('refuse' in classifyChange([file('src/old.ts', '', { status: 'deleted', kind: 'none', source: null }), file('src/l.ts', lines(9), { kind: 'symlink' })], unbound, [], tight)).toBe(false)
    expect(classifyChange([file('a.ts', 'x\n'), file('b.ts', 'x\n'), file('c.ts', 'x\n')], unbound, [], { ...CLASSIFY_LIMITS, maxFiles: 2 })).toEqual({ refuse: 'TOO_MANY_FILES' })
    expect(classifyChange(Array.from({ length: CLASSIFY_LIMITS.maxFiles + 1 }, (_, k) => file(`src/x${k}.ts`, '', { status: 'deleted', kind: 'none', source: null })), unbound, [])).toEqual({ refuse: 'TOO_MANY_FILES' })
  })
  test('a large untracked change at the limit is classified in seconds; one line more refuses the whole change before any verdict', () => {
    const half = facts(lines(CLASSIFY_LIMITS.maxChangedLines / 2))
    const atLimit = [{ ...file('src/a.ts', ''), source: half }, { ...file('src/b.ts', ''), source: half }]
    const { value, ms } = timed(() => classifyChange(atLimit, unbound, []))
    expect('refuse' in value ? value.refuse : value.lines.length).toBe(CLASSIFY_LIMITS.maxChangedLines)
    expect(ms).toBeLessThan(5000)
    const over = [...atLimit, { ...file('src/c.ts', ''), source: facts('x\n') }]
    const refused = timed(() => classifyChange(over, unbound, []))
    expect('refuse' in refused.value ? refused.value.refuse : `${refused.value.lines.length} verdicts`).toBe('TOO_MANY_LINES')
    expect(refused.ms).toBeLessThan(100)
  })
  test('changed lines that do not fit the file\'s text give a row and no verdict, never a line that does not exist', () => {
    for (const bad of [[0], [3], [1.5], [Number.NaN], [-1]]) {
      const c = classify([file('src/a.ts', 'a\nb\n', { status: 'modified', modified: bad })], unbound, [])
      expect([bad, c.files[0]!.reason, c.lines.length]).toEqual([bad, 'CHANGE_OUTSIDE_FILE', 0])
    }
  })
  test('a refused workload renders as unavailable with the limit in words, and no figure', () => {
    const view = unavailableEvidenceOf({ source: { head: 'a'.repeat(40), identity: null, tracked: 0, untracked: 3 }, base: { sha: 'b'.repeat(40), how: 'task-start', ancestor: true }, coverage: null, why: 'TOO_MANY_LINES' })
    const text = renderDiffEvidence(view, 80)
    expect(text).toContain('UNAVAILABLE: over 200,000 changed lines.')
    expect(text.split('\n').slice(-2)).toEqual([...CLOSING])
    expect(Object.values(view.counts).every(n => n === 0)).toBe(true)
    expect(renderDiffEvidence({ ...view, why: 'TOO_MANY_FILES' }, 80)).toContain('over 20,000 changed paths')
    expect(wordsOf('SOURCE_TOO_MANY_LINES')).toBe('not read: over 100,000 lines')
  })
})

